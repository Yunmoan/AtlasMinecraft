"""Translate the audited original pyramid geometry calls into static Go.

Development-only input is elm.java decompiled from the bundled 1.21.1 JAR.
The block constructor, chest and archaeology algorithms live in the hand-
ported structure_desert_pyramid.go; this emits only the original fixed calls.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "artifacts/worldgen-probes/remaining-source/elm.java"
OUTPUT = ROOT / "internal/worldgen/structure_pyramid_geometry.go"
BLOCKS = {"a": "air", "aV": "sandstone", "aW": "chiseled_sandstone", "aX": "cut_sandstone",
          "fD": "sandstone_stairs", "hk": "orange_terracotta", "dx": "stone_pressure_plate", "ck": "tnt",
          "jF": "sandstone_slab", "hu": "blue_terracotta"}
DIRECTIONS = {"c": "north", "d": "south", "e": "west", "f": "east"}


def expr(text: str) -> str:
    text = text.strip().replace("this.a", "21").replace("this.c", "21")
    text = re.sub(r"dga\.(\w+)\.o\(\)", lambda m: f'structureState("{BLOCKS[m[1]]}")', text)
    text = re.sub(r"\$\$(\d+)", r"v\1", text)
    return text


def main() -> None:
    java = SOURCE.read_text(encoding="utf-8")
    start = java.index("        this.a($$0, $$4, 0, -4, 0,")
    end = java.index("        for (ji $$18", start)
    result = ["// Code generated by docs/worldgen/build_pyramid_geometry.py from original 1.21.1 geometry; DO NOT EDIT.",
              "package worldgen", "", "func placeDesertPyramidGeometry(e *scatteredPieceEditor) {"]
    for line in java[start:end].splitlines():
        line = line.strip()
        if line == "}":
            result.append("}")
        elif line.startswith("for (int"):
            match = re.fullmatch(r"for \(int (\$\$\d+) = (.*); (.*); (.*)\) \{", line)
            if not match:
                raise ValueError(line)
            variable, initial, condition, increment = map(expr, match.groups())
            if increment.startswith("++"):
                increment = increment[2:] + "++"
            result.append(f"for {variable} := int32({initial}); {condition}; {increment} {{")
        elif line.startswith("int $$10"):
            continue
        elif line.startswith("dtc"):
            match = re.fullmatch(r"dtc (\$\$\d+) = \(dtc\)dga\.(\w+)\.o\(\)\.a\(dnt.b, ji\.(\w+)\);", line)
            if not match:
                raise ValueError(line)
            result.append(f'{expr(match[1])} := stateWithProperty(structureState("{BLOCKS[match[2]]}"), "facing", "{DIRECTIONS[match[3]]}")')
        elif line.startswith("this."):
            match = re.fullmatch(r"this\.([ab])\((.*)\);", line)
            if not match:
                raise ValueError(line)
            arguments = [item.strip() for item in match[2].split(",")]
            if arguments[0] != "$$0":
                raise ValueError(line)
            if arguments[1] == "$$4":
                values = arguments[2:]
                operation = "fill"
            else:
                values = arguments[1:-1]
                if arguments[-1] != "$$4":
                    raise ValueError(line)
                operation = "set" if match[1] == "a" else "fillDown"
            result.append(f'e.{operation}({", ".join(expr(value) for value in values)})')
        else:
            raise ValueError(f"unhandled original statement: {line}")
    result.append("}")
    OUTPUT.write_text("\n".join(result) + "\n", encoding="utf-8", newline="\n")
    print(f"generated {OUTPUT} from {end-start} original geometry characters")


if __name__ == "__main__":
    main()
