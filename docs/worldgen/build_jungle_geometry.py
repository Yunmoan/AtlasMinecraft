"""Translate audited original JungleTemplePiece calls to pure-Go geometry."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "artifacts/worldgen-probes/remaining-source/elt.java"
OUTPUT = ROOT / "internal/worldgen/structure_jungle_geometry.go"
BLOCKS = {"a":"air", "cQ":"cobblestone_stairs", "m":"cobblestone", "cn":"mossy_cobblestone", "fH":"tripwire_hook", "fI":"tripwire", "cw":"redstone_wire", "ff":"vine", "eK":"chiseled_stone_bricks", "dw":"lever", "br":"sticky_piston", "eh":"repeater"}
DIRECTIONS = {"a":"down", "b":"up", "c":"north", "d":"south", "e":"west", "f":"east"}
PROPERTIES = {"dnt.b":"facing", "doq.b":"facing", "doq.d":"attached", "dop.e":"north", "dop.f":"east", "dop.g":"south", "dop.h":"west", "dop.c":"attached", "dmb.b":"north", "dmb.c":"east", "dmb.d":"south", "dmb.e":"west", "dov.d":"east", "dov.e":"south", "dkl.aE":"facing", "dkl.K":"face", "dsv.a":"facing", "dmg.aE":"facing"}
FLAGS = {"j":"placedMainChest", "k":"placedHiddenChest", "l":"placedTrap1", "m":"placedTrap2"}

def split_args(text: str) -> list[str]:
    depth, start, values = 0, 0, []
    for index, char in enumerate(text):
        if char == "(": depth += 1
        elif char == ")": depth -= 1
        elif char == "," and depth == 0:
            values.append(text[start:index].strip()); start = index + 1
    values.append(text[start:].strip())
    return values

def unwrap(text: str) -> str:
    while text.startswith("("):
        depth = 0
        for index, char in enumerate(text):
            if char == "(": depth += 1
            elif char == ")": depth -= 1
            if depth == 0: break
        if index != len(text)-1: break
        text = text[1:-1]
    return text

def expr(text: str) -> str:
    text = unwrap(text.strip().replace("(dtc)", ""))
    if text.endswith(")") and ".a(" in text:
        index = text.rfind(".a(")
        prop, value = split_args(text[index+3:-1])
        if value.startswith("ji."): value = DIRECTIONS[value[3:]]
        elif value.startswith("duh."): value = {"a":"up", "b":"side", "c":"none"}[value[4:]]
        elif value.startswith("dtn."): value = {"a":"floor", "b":"wall", "c":"ceiling"}[value[4:]]
        return f'stateWithProperty({expr(text[:index])}, "{PROPERTIES[prop]}", "{value}")'
    if match := re.fullmatch(r"dga\.(\w+)\.o\(\)", text):
        return f'structureState("{BLOCKS[match[1]]}")'
    return re.sub(r"\$\$(\d+)", r"v\1", text.replace("this.a", "12").replace("this.c", "15"))

def main() -> None:
    java = SOURCE.read_text(encoding="utf-8")
    start = java.index("        this.a($$0, $$4, 0, -4, 0,")
    end = java.index("\n    }", start)
    result = ["// Code generated by docs/worldgen/build_jungle_geometry.py from original 1.21.1 geometry; DO NOT EDIT.", "package worldgen", "", "func placeJungleTempleGeometry(e *scatteredPieceEditor, world StructureBlockEntityWorld, random StructurePieceRandom) {"]
    skip_close = False
    for line in java[start:end].splitlines():
        line = line.strip()
        if line == "}":
            if skip_close: skip_close = False
            else: result.append("}")
        elif line.startswith("if (!this."):
            skip_close = True
        elif line.startswith("this.") and " = " in line:
            match = re.fullmatch(r"this\.([jklm]) = this\.a\((.*)\);", line)
            arguments = split_args(match[2]); coords = ", ".join(map(expr, arguments[3:6]))
            dispenser = len(arguments) == 8
            facing = DIRECTIONS[arguments[6][3:]] if dispenser else ""
            loot = "chests/jungle_temple_dispenser" if dispenser else "chests/jungle_temple"
            result.append(f'placeJungleLoot(e, world, random, "{FLAGS[match[1]]}", {coords}, "minecraft:{loot}", "{facing}")')
        elif line.startswith("for (int"):
            match = re.fullmatch(r"for \(int (\$\$\d+) = (.*); (.*); (.*)\) \{", line)
            variable, initial, condition, increment = map(expr, match.groups())
            if increment.startswith("++"): increment = increment[2:] + "++"
            result.append(f"for {variable} := int32({initial}); {condition}; {increment} {{")
        elif line.startswith("dtc "):
            match = re.fullmatch(r"dtc (\$\$\d+) = (.*);", line)
            result.append(f"{expr(match[1])} := {expr(match[2])}")
        elif line.startswith("this.a("):
            arguments = split_args(line[len("this.a("):-2])
            if arguments[0] != "$$0": raise ValueError(line)
            if arguments[1] == "$$4":
                if len(arguments) == 11:
                    if arguments[8:] != ["false", "$$3", "n"]: raise ValueError(line)
                    result.append(f'e.jungleFill(random, {", ".join(map(expr,arguments[2:8]))})')
                elif len(arguments) == 8:
                    air = 'structureState("air")'
                    result.append(f'e.fill({", ".join(map(expr,arguments[2:]))}, {air}, {air}, false)')
                else: raise ValueError(line)
            else:
                if len(arguments) != 6 or arguments[-1] != "$$4": raise ValueError(line)
                result.append(f'e.set({", ".join(map(expr,arguments[1:-1]))})')
        else: raise ValueError(f"unhandled original statement: {line}")
    result.append("}")
    OUTPUT.write_text("\n".join(result) + "\n", encoding="utf-8", newline="\n")
    print(f"generated {OUTPUT} from {end-start} original geometry characters")

if __name__ == "__main__": main()
